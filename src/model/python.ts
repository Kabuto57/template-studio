// Assembles fill_pptx.py: a docstring header, python/engine.py verbatim, then the template
// and settings as constants. The engine source is the real file, imported as text at build time.
import ENGINE_PY from "../../python/engine.py?raw";
import { describe, fieldType, projectForCode, type Model, type Project } from "./fields";

const SPLIT_MARKER = "# =========================================================================== command line";
/** Self-hosted Dify rejects Code node string outputs longer than this by default (CODE_MAX_STRING_LENGTH). */
export const DIFY_STRING_LIMIT = 80000;

export const isoDate = (d = new Date()): string =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

export function pyHeader(project: Project, model: Model, date = isoDate()): string {
  const rows: [string, string, string][] = [];
  for (const e of model.entries) {
    if (e.kind === "field") rows.push([e.name, fieldType(project, e) === "list" ? "list of text" : "text", describe(project, e.path)]);
    else if (e.kind === "object") e.children.forEach(c => rows.push([c.path, "text", describe(project, c.path)]));
    else if (e.scalar) rows.push([e.name, `list (up to ${e.max})`, describe(project, e.name + "[]")]);
    else {
      rows.push([e.name, `list of up to ${e.max} items`, describe(project, e.name + "[]")]);
      e.children.forEach(sub => rows.push([`  .${sub}`, "text", describe(project, `${e.name}[].${sub}`)]));
    }
  }
  model.calc.forEach(k => rows.push([k, "calculated", "filled in automatically"]));
  const w = Math.min(34, Math.max(10, ...rows.map(r => r[0].length)));
  const safe = (s: string) => s.replace(/"""/g, "'''").replace(/\\/g, "/");
  return [
    '"""',
    `${safe(project.name || "Presentation")} - fills the PowerPoint template with JSON.`,
    `Generated by Template Studio on ${date}. Standard library only (Python 3.8+).`,
    "",
    "DIFY CODE NODE (Python 3)",
    "    Input variable:   content_json (String)  <- the LLM node's text output",
    "    Output variables: pptx_base64 (String), file_name (String), status (String), message (String)",
    "",
    "YOUR LAPTOP",
    "    python fill_pptx.py content.json [output.pptx]",
    "",
    "FIELDS",
    ...rows.map(([k, t, d]) => safe(`    ${k.padEnd(w)}  ${t}${d ? " - " + d : ""}`)),
    "",
    "The template is embedded at the bottom (TEMPLATE_B64). To change it, edit it in",
    "Template Studio and copy the new code; open this file in Template Studio to keep editing.",
    '"""',
    "",
  ].join("\n");
}

export function buildPython(project: Project, model: Model, templateB64: string, date = isoDate()): string {
  const split = ENGINE_PY.indexOf(SPLIT_MARKER);
  const chunks = templateB64.match(/.{1,100}/g) ?? [""];
  const constants = [
    "# =========================================================================== template + settings (generated)",
    "",
    "PROJECT = json.loads(" + JSON.stringify(JSON.stringify(projectForCode(project))) + ")",
    "",
    "TEMPLATE_B64 = (",
    ...chunks.map(c => `    "${c}"`),
    ")",
    "",
    "",
  ].join("\n");
  return pyHeader(project, model, date) + ENGINE_PY.slice(0, split) + constants + ENGINE_PY.slice(split);
}

/** For display: collapse the embedded template so the code is readable. Copy still takes everything. */
export function displayPython(code: string): string {
  const ls = code.split("\n");
  const s = ls.findIndex(l => l.startsWith("TEMPLATE_B64 = ("));
  const e = ls.findIndex((l, i) => i > s && l === ")");
  if (s < 0 || e - s < 6) return code;
  return [...ls.slice(0, s + 3), `    # ... ${e - s - 4} more lines of the embedded template (included when you copy) ...`, ls[e - 1]!, ...ls.slice(e)].join("\n");
}

/** Read the template and settings back out of a fill_pptx.py made by this app or by pptx_kit.py. */
export function parsePythonFile(code: string): { project: Partial<Project>; templateB64: string } {
  const pm = /^PROJECT = json\.loads\((".*")\)\s*$/m.exec(code);
  const tm = /^TEMPLATE_B64 = \(\r?\n([\s\S]*?)\r?\n\)/m.exec(code);
  if (!pm || !tm) throw new Error("This .py file wasn't made by Template Studio.");
  return {
    project: JSON.parse(JSON.parse(pm[1]!) as string) as Partial<Project>,
    templateB64: [...tm[1]!.matchAll(/"([A-Za-z0-9+/=]*)"/g)].map(m => m[1]).join(""),
  };
}
