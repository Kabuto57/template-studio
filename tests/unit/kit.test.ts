    const sel = { obj: idx, cell: null };
    expect(setText(deck, 0, sel, "Intro\n{{text}}\nThird")).toBe(true);
    expect(setStyle(deck, 0, sel, { sz: 20, b: true, i: true, color: "112233", algn: "ctr", font: "Georgia", fill: "EEEEEE" })).toBe(true);
    const sp = objs()[idx]!;
    const paras = [...sp.getElementsByTagName("*")].filter(e => e.localName === "p");
    expect(paras.length).toBe(3);
    for (const p of paras) expect(p.firstElementChild!.localName).toBe("pPr");
    const rPr = [...sp.getElementsByTagName("*")].find(e => e.localName === "rPr")!;
