const written: string[] = [];
const write = (name: string, data: Uint8Array | string): string => {
  const f = join(OUT, name);
  writeFileSync(f, data);
  if (name.endsWith(".pptx")) written.push(f);
  return f;
};

async function filled(deck: Deck, data: Data, project: Project): Promise<Uint8Array> {
  const z = await Zip.load(await deck.bytes());
  const report = newReport();
  for (const [n, x] of Object.entries(deck.texts)) if (isSlidePart(n)) z.set(n, fillXml(x, data, report, project.settings.colour_rules));
  return z.generate();
}

/** Run a pptx_kit.py against the sample in a scratch folder and return the kit folder. */
function runKit(label: string, kitSource: string): string {
  const dir = join(OUT, label);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "pptx_kit.py"), kitSource);
  cpSync(join(ROOT, "src/assets/sample_template.pptx"), join(dir, "template.pptx"));
  writeFileSync(join(dir, "fields.json"), JSON.stringify(projectForCode(sampleProject), null, 2));
  py(["-I", "-S", join(dir, "pptx_kit.py"), "build", join(dir, "template.pptx")]);
  return join(dir, "template_kit");
}
const read = (...p: string[]) => readFileSync(join(...p), "utf8");
/** The parts of fill_pptx.py that do not depend on the template bytes, the settings blob or today's date. */
const stable = (code: string) => code
  .replace(/^Generated by Template Studio on \d{4}-\d\d-\d\d\./m, "Generated by Template Studio on DATE.")
  .replace(/^PROJECT = .*$/m, "PROJECT = ...")
  .replace(/^TEMPLATE_B64 = \(\n[\s\S]*?\n\)/m, "TEMPLATE_B64 = (...)");

describe("the audit sample", () => {
  let deck: Deck;
  beforeAll(async () => { deck = await Deck.load(sampleBytes); });

  it("loads slides in presentation order with the theme", () => {
    expect(deck.slides.map(s => s.path)).toEqual(["ppt/slides/slide1.xml", "ppt/slides/slide2.xml"]);
    expect(deck.W / deck.H).toBeCloseTo(16 / 9, 2);
    expect(Object.keys(deck.theme)).toContain("accent1");
  });

  it("derives the field model from the template", () => {
    const m = buildModel(deck.scan());
    expect(m.entries.filter(e => e.kind === "field").map(e => e.name)).toEqual(expect.arrayContaining(["report_title", "executive_summary", "key_highlights"]));
    const findings = m.entries.find(e => e.name === "findings");
    expect(findings).toMatchObject({ kind: "array", scalar: false, children: ["title", "risk", "recommendation", "owner", "due_date"] });
    expect(m.calc).toEqual(expect.arrayContaining(["count:findings", "count:findings.risk=High"]));
  });

  it("renders every slide to HTML with field tokens", () => {
    deck.slides.forEach((_, i) => {
      const el = renderSlide(deck, i, { highlight: true, editable: true });
      expect(el.querySelectorAll(".ph").length).toBeGreaterThan(3);
      expect(el.querySelectorAll("[data-obj]").length).toBeGreaterThan(3);
    });
    expect(renderSlide(deck, 1, { editable: true }).querySelectorAll("td.hit").length).toBeGreaterThan(10);
  });

  describe("generated outputs", () => {
    const model = () => buildModel(deck.scan());
    const example = () => JSON.stringify(buildExample(sampleProject, model()), null, 2);
    const schema = () => JSON.stringify(buildSchema(sampleProject, model()), null, 2);
    const prompt = () => buildPrompt(sampleProject, model());

    it("match the prototype's pptx_kit.py (golden reference)", () => {
      // The prototype calls Path.write_text(newline=...), which only exists from Python 3.10 although it
      // promises 3.8. Drop that one argument so the reference also runs on 3.8; on Linux and macOS the
      // files it writes are identical either way.
      const kit = runKit("golden_prototype", read(ROOT, "reference/built/pptx_kit.py").replace('encoding="utf-8", newline="\\n")', 'encoding="utf-8")'));
      expect(example() + "\n").toBe(read(kit, "example_body.json"));
      expect(schema() + "\n").toBe(read(kit, "json_schema.json"));
      expect(prompt() + "\n").toBe(read(kit, "llm_prompt.txt"));
      // the docstring header of fill_pptx.py is generated separately in both; it must agree too
      const header = (code: string) => stable(code).slice(0, code.indexOf('"""\n', 5));
      expect(header(buildPython(sampleProject, model(), "AAAA"))).toBe(header(read(kit, "fill_pptx.py")));
    });

    it("match this repo's pptx_kit.py, including the whole Python file", () => {
      const kit = runKit("golden_current", buildKit(ROOT));
      expect(example() + "\n").toBe(read(kit, "example_body.json"));
      expect(schema() + "\n").toBe(read(kit, "json_schema.json"));
      expect(prompt() + "\n").toBe(read(kit, "llm_prompt.txt"));
      expect(stable(buildPython(sampleProject, model(), "AAAA"))).toBe(stable(read(kit, "fill_pptx.py")));
      written.push(join(kit, "preview.pptx"));
    });

    it("produce a schema that describes the example", () => {
      const s = buildSchema(sampleProject, model()) as { required: string[]; properties: Record<string, { type: string; enum?: string[]; maxItems?: number }> };
      const ex = buildExample(sampleProject, model());
      expect(s.required).toEqual(Object.keys(ex));
      expect(s.properties.overall_rating!.enum).toEqual(["Satisfactory", "Needs Improvement", "Unsatisfactory"]);
      expect(s.properties.findings).toMatchObject({ type: "array", minItems: 1, maxItems: 5 });
      expect(s.properties.key_highlights!.type).toBe("array");
    });

    it("embed the engine verbatim and round-trip through 'open a .py file'", async () => {
      const b64 = bytesToB64(await deck.bytes());
      const code = buildPython(sampleProject, model(), b64, "2026-01-02");
      const engine = read(ROOT, "python/engine.py");
      const split = engine.indexOf("# =========================================================================== command line");
      expect(code).toContain(engine.slice(0, split));
      expect(code.endsWith(engine.slice(split))).toBe(true);
      expect(code).toContain("Generated by Template Studio on 2026-01-02.");
      const back = parsePythonFile(code);
      expect(back.templateB64).toBe(b64);
      expect(back.project).toEqual(projectForCode(sampleProject));
      expect(displayPython(code).split("\n").length).toBeLessThan(code.split("\n").length);
      expect(() => parsePythonFile("print('hi')")).toThrow(/wasn't made by Template Studio/);
    });
  });

  describe("the generated fill_pptx.py", () => {
    let codeFile: string, dataFile: string;
    beforeAll(async () => {
      codeFile = write("fill_pptx.py", buildPython(sampleProject, buildModel(deck.scan()), bytesToB64(await deck.bytes())));
      dataFile = write("sample_data.json", JSON.stringify(sampleData));
    });
    const dify = (data: string, out: string) => JSON.parse(py(["-I", "-S", "tests/py/dify_run.py", codeFile, data, join(OUT, out)])) as Record<string, unknown>;

    it("runs like a Dify Code node, with the standard library only", () => {
      const r = dify(dataFile, "dify_filled.pptx");
      expect(r).toMatchObject({ status: "success", file_name: "Procurement_Process_Audit.pptx", message: "All fields filled.", stdlib_only: true });
      expect(r.bytes).toBeGreaterThan(5000);
      written.push(join(OUT, "dify_filled.pptx"));
    });

    it("produces exactly the slide XML the browser preview shows", async () => {
      const fromPython = await Zip.load(bytes("tests/py/out/dify_filled.pptx"));
      for (const [name, xml] of Object.entries(deck.texts)) {
        if (!isSlidePart(name)) continue;
        expect(await fromPython.text(name), name).toBe(fillXml(xml, sampleData, newReport(), sampleProject.settings.colour_rules));
      }
    });

    it("reports fields the JSON left out, and accepts ```json fences", () => {
      const partial = write("partial.json", "```json\n" + JSON.stringify({ report_title: "Only a title", findings: [] }) + "\n```");
      const r = dify(partial, "dify_partial.pptx");
      expect(r.status).toBe("success");
      expect(r.file_name).toBe("Only_a_title.pptx");
      expect(r.message).toMatch(/^Left blank \(not in the JSON\): .*executive_summary/);
      written.push(join(OUT, "dify_partial.pptx"));
    });

    it("returns an error result instead of raising on invalid JSON", () => {
      const r = dify("--bad", "never.pptx");
      expect(r).toMatchObject({ status: "error", file_name: "", bytes: 0 });
      expect(r.message).toMatch(/^Could not build the presentation: /);
    });

    it("works from the command line on a laptop", () => {
      const out = join(OUT, "cli_filled.pptx");
      const r = spawnSync(PYTHON, ["-I", "-S", codeFile, dataFile, out], { encoding: "utf8" });
      expect(r.status, r.stderr).toBe(0);
      expect(r.stdout).toContain("Saved");
      expect(readFileSync(out).equals(readFileSync(join(OUT, "dify_filled.pptx")))).toBe(true);
      // Dify's HTTP body shape {"content_json": "..."} is accepted too
      const wrapped = write("wrapped.json", JSON.stringify({ content_json: JSON.stringify(sampleData) }));
      expect(spawnSync(PYTHON, ["-I", "-S", codeFile, wrapped, join(OUT, "cli_wrapped.pptx")], { encoding: "utf8" }).status).toBe(0);
      written.push(out);
    });
  });
});

