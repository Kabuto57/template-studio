    expect(tableOp(deck, 0, { obj: table, cell: null }, "addCol")).toBe("Column added");
    expect(keys()).toContain("rows.4.column");
    expect(tableOp(deck, 0, { obj: table, cell: null }, "delRow")).toBeNull(); // needs a selected cell
    expect(tableOp(deck, 0, { obj: table, cell: cellsOfRow2[0]!.i }, "delRow")).toMatch(/Row deleted/);
